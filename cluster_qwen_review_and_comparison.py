import urllib.request
import json
import sys
import os
import time

sys.stdout.reconfigure(encoding='utf-8')

GATEWAY_URL = "http://localhost:8080/v1/chat/completions"
MODEL = "qwen3.8:27b"

# Load previous review from Gemma 4
prev_review = ""
if os.path.exists("docs/ARCHITECTURE_AND_MODULARITY_REVIEW.md"):
    with open("docs/ARCHITECTURE_AND_MODULARITY_REVIEW.md", "r", encoding="utf-8") as f:
        prev_review = f.read()

prompt = f"""You are Qwen 3.8 (27B), the Lead Reasoning and Deep Architectural Audit Model for this local agent cluster.

Here is the prior architectural review generated by Gemma 4:
=== PRIOR GEMMA 4 REVIEW ===
{prev_review[:3500]}
============================

Current Codebase State of AgentTrace Gateway (`src/`):
- `src/lib.rs`: Module exports.
- `src/main.rs`: Setup, Axum server, SQLite WAL db, background watchers. Upstream timeout was just raised to 300s.
- `src/handlers.rs`: Axum endpoints for dashboard, /flyer, telemetry events, policies, delegation overrides, SSE streaming.
- `src/proxy.rs`: OpenAI reverse proxy (/v1/chat/completions), delegation engine hook, upstream allowlist check.
- `src/delegation_engine.rs`: Dynamic route overrides (Session, Agent, Tag, Model, PromptPattern), FallbackSwitch, CloudInterception.
- `src/registry.rs`: Dynamic cluster node registration, model capability derivation, offline node failover.
- `src/router.rs`: Prompt intent classification (Math, Fast Code, Verification, Cloud fallback).
- `src/policy.rs`: Granular sandbox access control (Read/Write/Network whitelists, .env blacklist, blast radius score).
- `src/ledger.rs`: Ed25519 cryptographic signing & verification, SHA-256 V2 length-prefixed canonical hash chaining.
- `src/secrets.rs`: Cluster security config, Bearer auth tokens, SSRF upstream URL allowlist.
- `src/agent_interface.rs`: MCP (Model Context Protocol) JSON-RPC handler, tool dispatch, override controls.
- `src/analytics.rs`: Read/write ratios, blast radius threat formulas.
- `src/schema.rs`: TraceEvent, NodeHeartbeat, SecurityVerdict, EventType, ClusterSummary.
- `src/services.rs`: Model introspector, discovery beacon, worker forwarder.

Recently added unit tests:
- `src/secrets.rs`: Permissive auth, Bearer tokens, custom headers, SSRF allowlists.
- `src/ledger.rs`: Genesis hash, keypair sign/verify, tampered sigs/hashes rejected, V2 determinism.
- `src/policy.rs`: Non-enforcing audit mode, network whitelists, wildcard pattern matching.

YOUR TASKS:
1. **Deep Architectural & Modularity Re-check**:
   - Re-evaluate the architecture, component cohesion, and modularity.
   - Point out what was missed by previous reviews with specific code examples.
2. **Model Comparison: What Each Model Caught**:
   - Explicitly detail what **Gemma 4** caught vs. what **Qwen 3.8** caught vs. what **DeepSeek R1** caught.
   - Give specific examples, concrete anti-patterns, and code references for each.
3. **Concrete Missing Unit Tests to Implement**:
   - Provide concrete, copy-pasteable Rust `#[test]` implementations for:
     a) `schema.rs`: JSON serialization/deserialization round-trips for `TraceEvent`, `SecurityVerdict`, `NodeHeartbeat`.
     b) `agent_interface.rs`: MCP JSON-RPC protocol parsing (`tools/list`, `tools/call`, error formats).
     c) `delegation_engine.rs`: Advanced wildcard matching and priority rules.
     d) `proxy.rs` / `handlers.rs`: Header extraction and query parameter parsing.

Write the report in thorough, authoritative, professional Markdown.
"""

payload = {
    "model": MODEL,
    "messages": [
        {
            "role": "system",
            "content": "You are Qwen 3.8 (27B), Lead Systems Architect and Code Quality Inspector. Output a deep, structured architectural report with specific model comparisons and ready-to-run Rust unit tests."
        },
        {
            "role": "user",
            "content": prompt
        }
    ],
    "max_tokens": 2500,
    "temperature": 0.4
}

print(f"[*] Delegating Deep Re-Check & Model Comparison to {MODEL} via Gateway ({GATEWAY_URL})...")
t0 = time.time()

req = urllib.request.Request(
    GATEWAY_URL,
    data=json.dumps(payload).encode("utf-8"),
    headers={"Content-Type": "application/json"}
)

try:
    with urllib.request.urlopen(req, timeout=300) as resp:
        res = json.loads(resp.read().decode("utf-8"))
        content = res["choices"][0]["message"]["content"]
        elapsed = time.time() - t0
        
        print(f"[+] Qwen 3.8 (27B) review complete in {elapsed:.2f}s!")
        
        os.makedirs("docs", exist_ok=True)
        report_path = os.path.join("docs", "QWEN_ARCHITECTURE_AND_MODEL_COMPARISON.md")
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"[+] Saved comparison report to: {report_path}")
        
        print("\n--- REPORT PREVIEW ---")
        lines = [l for l in content.splitlines() if l.strip()]
        for l in lines[:20]:
            print(l)

except Exception as e:
    print(f"[-] Error during Qwen 3.8 delegation: {e}")
    sys.exit(1)
