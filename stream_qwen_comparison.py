import urllib.request
import json
import sys
import os
import time

sys.stdout.reconfigure(encoding='utf-8')

prev_review = ""
if os.path.exists("docs/ARCHITECTURE_AND_MODULARITY_REVIEW.md"):
    with open("docs/ARCHITECTURE_AND_MODULARITY_REVIEW.md", "r", encoding="utf-8") as f:
        prev_review = f.read()

prompt = f"""You are Qwen 3.8 (27B), the heavy local reasoning architect on PC-1.

Here is the architectural review generated by Gemma 4:
=== GEMMA 4 REVIEW ===
{prev_review[:3000]}
======================

System: AgentTrace Gateway (`src/lib.rs`, `src/main.rs`, `src/handlers.rs`, `src/proxy.rs`, `src/delegation_engine.rs`, `src/registry.rs`, `src/router.rs`, `src/policy.rs`, `src/ledger.rs`, `src/secrets.rs`, `src/agent_interface.rs`, `src/schema.rs`, `src/analytics.rs`).

Recently added unit tests:
- `src/secrets.rs`: Auth permissive mode, Bearer headers, SSRF allowlists.
- `src/ledger.rs`: Ed25519 keypair generation, V2 canonical hash determinism, signature tampering rejection.
- `src/policy.rs`: Non-enforcing audit mode, network allowlists, wildcard glob matching.

YOUR OBJECTIVE:
Produce a detailed comparison report contrasting **Gemma 4** vs **Qwen 3.8 (27B)** findings on the AgentTrace Gateway architecture.

REQUIRED SECTIONS:
1. **Executive Contrast: Analytical Styles of Gemma 4 vs Qwen 3.8**:
   - How did Gemma 4 approach the codebase (macro structure, service boundaries, contracts)?
   - How does Qwen 3.8 approach the codebase (deep data-flow invariants, concurrency traps, subtle race conditions, protocol corner cases)?

2. **Side-by-Side Breakdown: What Each Model Caught (With Concrete Examples)**:
   - Provide a clear comparison table or detailed bulleted breakdown showing:
     * Category (e.g. Modularity, State/Concurrency, Security/Policy, Protocols/MCP)
     * What **Gemma 4** caught (with specific code concept or file reference)
     * What **Qwen 3.8** caught (with specific code concept, line/file reference, or anti-pattern)
   - Include concrete code examples showing the specific issues each model identified.

3. **Qwen 3.8 Deep Architectural Findings (Beyond Gemma 4)**:
   - Specific flaws or improvement areas in `agent_interface.rs` (MCP JSON-RPC parsing, error structures).
   - Specific flaws or improvement areas in `delegation_engine.rs` (rule priority resolution, tie-breaking, wildcard edge cases).
   - Specific flaws in `proxy.rs` (header forwarding, connection reuse, stream error propagation).

4. **Concrete Additional Unit Tests to Add**:
   - Provide syntactically valid Rust unit test code blocks ready to be added for:
     * `schema.rs` (TraceEvent and SecurityVerdict serde roundtrips)
     * `agent_interface.rs` (MCP RPC request structure and validation)
     * `delegation_engine.rs` (Rule priority and tag matching)

Write the complete markdown document now.
"""

payload = {
    "model": "qwen3.8:27b",
    "messages": [
        {"role": "system", "content": "You are Qwen 3.8 (27B), Principal Systems Architect. Produce a comprehensive, technical comparison report with concrete code examples."},
        {"role": "user", "content": prompt}
    ],
    "stream": True,
    "options": {
        "temperature": 0.3,
        "num_predict": 2500
    }
}

print("[*] Streaming audit & comparison from Qwen 3.8 (27B) on PC-1 Ollama (zero-token)...")
t0 = time.time()

req = urllib.request.Request(
    "http://127.0.0.1:11434/api/chat",
    data=json.dumps(payload).encode("utf-8"),
    headers={"Content-Type": "application/json"}
)

report_path = "docs/QWEN_ARCHITECTURE_AND_MODEL_COMPARISON.md"
os.makedirs("docs", exist_ok=True)

try:
    with urllib.request.urlopen(req, timeout=600) as resp:
        with open(report_path, "w", encoding="utf-8") as out_f:
            total_chars = 0
            for line in resp:
                if not line:
                    continue
                try:
                    chunk = json.loads(line.decode("utf-8"))
                    text = chunk.get("message", {}).get("content", "")
                    if text:
                        out_f.write(text)
                        out_f.flush()
                        total_chars += len(text)
                    if chunk.get("done", False):
                        break
                except Exception:
                    continue

    elapsed = time.time() - t0
    print(f"[+] Qwen 3.8 stream completed in {elapsed:.2f}s! Total characters written: {total_chars}")
    print(f"[+] Saved to: {report_path}")

except Exception as e:
    print(f"[-] Error during streaming from Qwen 3.8: {e}")
    sys.exit(1)
